def add_scratch_with_mask(img):
    h, w = img.shape[:2]
    mask = np.zeros((h, w), dtype=np.uint8)
    img_aug = img.copy()
    for _ in range(random.randint(1, 5)):
        x1, y1 = random.randint(0, w), random.randint(0, h)
        x2, y2 = x1 + random.randint(30, 100), y1 + random.randint(-20, 20)
        cv2.line(img_aug, (x1, y1), (x2, y2), (0, 0, 0), thickness=1)
        cv2.line(mask, (x1, y1), (x2, y2), 255, thickness=1)
    return img_aug, mask

def add_stain_with_mask(img):
    h, w = img.shape[:2]
    img_aug = img.copy()
    mask = np.zeros((h, w), dtype=np.uint8)
    stain = np.zeros_like(img)
    for _ in range(random.randint(1, 3)):
        center = (random.randint(0, w), random.randint(0, h))
        axes = (random.randint(10, 30), random.randint(10, 30))
        color = tuple([random.randint(30, 80) for _ in range(3)])
        cv2.ellipse(stain, center, axes, 0, 0, 360, color, -1)
        cv2.ellipse(mask, center, axes, 0, 0, 360, 255, -1)
    img_aug = cv2.addWeighted(img_aug, 1, stain, 0.5, 0)
    return img_aug, mask

def generate_defect_with_mask(img):
    return random.choice([add_scratch_with_mask, add_stain_with_mask])(img)

def augment_mvtec_with_mask(mvtec_root, class_name, num_per_image=3):
    input_dir = os.path.join(mvtec_root, class_name, "train", "good")
    test_output_dir = os.path.join(mvtec_root, class_name, "test", "synthetic")
    mask_output_dir = os.path.join(mvtec_root, class_name, "ground_truth", "synthetic")
    os.makedirs(test_output_dir, exist_ok=True)
    os.makedirs(mask_output_dir, exist_ok=True)
    image_paths = glob.glob(os.path.join(input_dir, "*.png")) + glob.glob(os.path.join(input_dir, "*.jpg"))
    for img_path in image_paths:
        img = cv2.imread(img_path)
        img_name = os.path.splitext(os.path.basename(img_path))[0]
        for i in range(num_per_image):
            defect_img, mask = generate_defect_with_mask(img)
            img_file = f"{img_name}_defect{i+1}.png"
            mask_file = f"{img_name}_defect{i+1}_mask.png"
            cv2.imwrite(os.path.join(test_output_dir, img_file), defect_img)
            cv2.imwrite(os.path.join(mask_output_dir, mask_file), mask)

