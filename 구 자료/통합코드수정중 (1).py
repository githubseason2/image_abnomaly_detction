class GridFeedbackTool:
    def __init__(self, root, image_paths, save_dir, grid_size=3, image_size=220):
        self.root = root
        self.image_paths = image_paths
        self.save_dir = save_dir
        self.grid_size = grid_size
        self.image_size = image_size
        self.index = 0
        self.selected = {}
        self.feedback = {}
        self.root.title("사용자 피드백 툴")
        self.root.geometry(f"{grid_size * (image_size + 40)}x{grid_size * (image_size + 60) + 60}")
        self.root.configure(bg="white")
        self.frame = Frame(root, bg="white")
        self.frame.pack(pady=20)
        button_frame = Frame(root, bg="white")
        button_frame.pack(pady=5)
        Button(button_frame, text="다음 →", command=self.save_and_next).pack(side=LEFT, padx=10)
        Button(button_frame, text="저장 후 종료", command=self.save_and_quit).pack(side=LEFT, padx=10)
        Button(button_frame, text="종료", command=self.quit_without_saving).pack(side=LEFT, padx=10)
        self.root.bind("<s>", lambda e: self.save_and_quit())
        self.root.bind("<Escape>", lambda e: self.quit_without_saving())
        self.root.bind("<q>", lambda e: self.quit_without_saving())
        self.load_images()

    def load_images(self):
        for widget in self.frame.winfo_children():
            widget.destroy()
        self.current_batch = self.image_paths[self.index:self.index + self.grid_size**2]
        for idx, path in enumerate(self.current_batch):
            img = PILImage.open(path).resize((self.image_size, self.image_size))
            tk_img = PILImageTk.PhotoImage(img)
            label_frame = Frame(self.frame, bd=4, relief="solid")
            label_frame.grid(row=idx // self.grid_size, column=idx % self.grid_size, padx=10, pady=10)
            label = Label(label_frame, image=tk_img)
            label.image = tk_img
            label.pack()
            label.bind("<Button-1>", lambda e, p=path: self.toggle(p))
            label_frame.config(highlightthickness=4, highlightbackground=self.get_highlight_color(self.selected.get(path)))

    def get_highlight_color(self, status):
        return {"defect": "red", "good": "green"}.get(status, "gray")

    def toggle(self, path):
        current = self.selected.get(path)
        if current == "defect":
            self.selected[path] = "good"
        elif current == "good":
            del self.selected[path]
        else:
            self.selected[path] = "defect"
        self.load_images()

    def save_and_next(self):
        self.store_current_batch_feedback()
        self.index += self.grid_size**2
        if self.index < len(self.image_paths):
            self.load_images()
        else:
            self.save_feedback()
            self.root.quit()

    def save_and_quit(self):
        self.store_current_batch_feedback()
        self.save_feedback()
        self.root.quit()

    def quit_without_saving(self):
        self.root.quit()

    def store_current_batch_feedback(self):
        for path in self.current_batch:
            label = self.selected.get(path, "undecided")
            self.feedback[path] = label

    def save_feedback(self):
        os.makedirs(self.save_dir, exist_ok=True)
        txt_path = os.path.join(self.save_dir, "feedback.txt")
        json_path = os.path.join(self.save_dir, "feedback.json")
        with open(txt_path, "w") as f:
            for path, label in self.feedback.items():
                f.write(f"{path}\t{label}\n")
        with open(json_path, "w") as jf:
            json.dump(self.feedback, jf, indent=4)

