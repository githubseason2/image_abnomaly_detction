# ----------------------- Data Loader -----------------------
class MVTecGoodDataset(Dataset):
    def __init__(self, root_dir, transform=None):
        self.image_paths = sorted(glob.glob(os.path.join(root_dir, "*.png"))) + \
                           sorted(glob.glob(os.path.join(root_dir, "*.jpg")))
        self.transform = transform

    def __len__(self):
        return len(self.image_paths)

    def __getitem__(self, idx):
        img_path = self.image_paths[idx]
        image = Image.open(img_path).convert("RGB")
        if self.transform:
            image = self.transform(image)
        return image, 0  # dummy label

# -------------------- LAS Augmentation ---------------------
def apply_las_augmentation(image, patch_size=64, stride=32):
    _, c, h, w = image.shape
    patches = []
    for i in range(0, h - patch_size + 1, stride):
        for j in range(0, w - patch_size + 1, stride):
            patch = image[:, :, i:i+patch_size, j:j+patch_size]
            patches.append(patch)
    random.shuffle(patches)
    new_image = torch.zeros_like(image)
    patch_idx = 0
    for i in range(0, h - patch_size + 1, stride):
        for j in range(0, w - patch_size + 1, stride):
            new_image[:, :, i:i+patch_size, j:j+patch_size] = patches[patch_idx]
            patch_idx += 1
    return new_image

# -------------------- GAS Augmentation ---------------------
def gas_augmentation_wrn(image, model=None, target_layer='layer4', steps=10, lr=0.01):
    image = image.clone().detach().requires_grad_(True)
    if model is None:
        model = wide_resnet50_2(pretrained=True)
        model.eval()
    activation = {}
    def hook_fn(module, input, output):
        activation['act'] = output
    handle = dict(model.named_modules())[target_layer].register_forward_hook(hook_fn)
    optimizer = torch.optim.SGD([image], lr=lr)
    for _ in range(steps):
        optimizer.zero_grad()
        model(image)
        act = activation['act']
        loss = -act.norm(p=2)
        loss.backward()
        optimizer.step()
    handle.remove()
    return image.detach()

# ---------------------- Save Augmented ---------------------
def save_augmented_dataset(data_path, save_root, las_fn, gas_fn, max_images=50):
    transform = transforms.Compose([transforms.Resize((256, 256)), transforms.ToTensor()])
    dataset = MVTecGoodDataset(data_path, transform)
    loader = DataLoader(dataset, batch_size=1, shuffle=True)
    os.makedirs(save_root, exist_ok=True)
    for sub in ["original", "las", "gas"]:
        os.makedirs(os.path.join(save_root, sub), exist_ok=True)
    model = wide_resnet50_2(pretrained=True).eval()
    for idx, (image, _) in enumerate(tqdm(loader)):
        if idx >= max_images:
            break
        image = image.cuda() if torch.cuda.is_available() else image
        las_img = las_fn(image)
        gas_img = gas_fn(image, model=model)
        save_image(image, os.path.join(save_root, "original", f"{idx:04d}.png"))
        save_image(las_img, os.path.join(save_root, "las", f"{idx:04d}.png"))
        save_image(gas_img, os.path.join(save_root, "gas", f"{idx:04d}.png"))

